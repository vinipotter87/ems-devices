function norm(s: string): string { return s.normalize("NFD").replace(/[\u0300-\u036f]/g, "").toLowerCase().trim(); }
export function buscarCidades(q: string, limite = 8): Cidade[] {
  const n = norm(q); if (!n) return [];
  // Cobertas antes das fora da cobertura; dentro de cada grupo, mais UTCs primeiro.
  const peso = (c: Cidade) => (c.distrito === "990" ? 0 : 1_000_000) + c.utcs;
  const starts = CIDADES.filter((c) => norm(c.nome).startsWith(n)).sort((a, b) => peso(b) - peso(a));
  const contains = CIDADES.filter((c) => !norm(c.nome).startsWith(n) && norm(c.rotulo).includes(n)).sort((a, b) => peso(b) - peso(a));
  return [...starts, ...contains].slice(0, limite);
}
export function acharCidade(nome: string, uf: string): Cidade | undefined {
  const n = norm(nome); return CIDADES.find((c) => norm(c.nome) === n && c.uf === uf.toUpperCase());
}
